CREATE TABLE SALARY_HISTORY (
    EMP_ID NUMBER,
    OLD_SALARY NUMBER,
    NEW_SALARY NUMBER,
    CHANGE_DATE DATE
);

CREATE OR REPLACE TRIGGER trg_salary_history
AFTER UPDATE OF SAL ON EMP
FOR EACH ROW
WHEN (OLD.SAL <> NEW.SAL)
BEGIN
    INSERT INTO SALARY_HISTORY
    VALUES (
        :OLD.EMPNO,
        :OLD.SAL,
        :NEW.SAL,
        SYSDATE
    );
END;
