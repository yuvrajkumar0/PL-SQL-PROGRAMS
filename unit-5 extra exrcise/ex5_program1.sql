SET SERVEROUTPUT ON;

CREATE TABLE EMP_AUDIT (
    EMPNO NUMBER,
    ENAME VARCHAR2(50),
    SAL NUMBER,
    DEPTNO NUMBER,
    ACTION_DATE DATE
);

CREATE OR REPLACE TRIGGER trg_emp_insert
AFTER INSERT ON EMP
FOR EACH ROW
BEGIN
    INSERT INTO EMP_AUDIT
    VALUES (
        :NEW.EMPNO,
        :NEW.ENAME,
        :NEW.SAL,
        :NEW.DEPTNO,
        SYSDATE
    );
END;
