SET SERVEROUTPUT ON;

CREATE TABLE SALARY_AUDIT (
    EMPNO NUMBER,
    OLD_SALARY NUMBER,
    NEW_SALARY NUMBER,
    CHANGE_DATE DATE
);

CREATE OR REPLACE TRIGGER trg_salary_update
AFTER UPDATE OF SAL ON EMP
FOR EACH ROW
BEGIN
    INSERT INTO SALARY_AUDIT
    VALUES (
        :OLD.EMPNO,
        :OLD.SAL,
        :NEW.SAL,
        SYSDATE
    );
END;
