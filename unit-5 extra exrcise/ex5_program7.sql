CREATE TABLE SALARY_CHANGE_LOG (
    EMPNO NUMBER,
    OLD_SALARY NUMBER,
    NEW_SALARY NUMBER,
    CHANGE_DATE DATE
);

CREATE OR REPLACE TRIGGER trg_salary_change_log
AFTER UPDATE OF SAL ON EMP
FOR EACH ROW
WHEN (OLD.SAL <> NEW.SAL)
BEGIN
    INSERT INTO SALARY_CHANGE_LOG
    VALUES (
        :OLD.EMPNO,
        :OLD.SAL,
        :NEW.SAL,
        SYSDATE
    );
END;
