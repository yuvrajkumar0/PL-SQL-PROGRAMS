SET SERVEROUTPUT ON;

CREATE TABLE EMP_DELETE_AUDIT (
    EMPNO NUMBER,
    ENAME VARCHAR2(50),
    SAL NUMBER,
    DEPTNO NUMBER,
    DELETE_DATE DATE
);

CREATE OR REPLACE TRIGGER trg_emp_delete
AFTER DELETE ON EMP
FOR EACH ROW
BEGIN
    INSERT INTO EMP_DELETE_AUDIT
    VALUES (
        :OLD.EMPNO,
        :OLD.ENAME,
        :OLD.SAL,
        :OLD.DEPTNO,
        SYSDATE
    );
END;
